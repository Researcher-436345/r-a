// PDFBehavior describes how the fake serves a paper's PDF.
type PDFBehavior string

const (
	PDFOK          PDFBehavior = "ok"          // serve the fixture bytes
	PDFUnavailable PDFBehavior = "unavailable" // 503 forever ("publisher is down")
	PDFNotPDF      PDFBehavior = "html"        // 200 with an HTML body ("bot wall")
)

// Paper is one arXiv record the fake knows about.
type Paper struct {
	ID        string // canonical arXiv id, no version suffix
	Title     string
	Abstract  string
	Authors   []string
	Published time.Time
	Updated   time.Time
	PDF       string // fixture file name under fixtures/pdf
	Behavior  PDFBehavior
	// EPrint, when set, is served as the TeX source (tar.gz); otherwise 404
	// so the worker falls back to the PDF parser.
	EPrint []byte
}

