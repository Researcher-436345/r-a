// Synthetic DOIs, like synthetic arXiv ids, give a scenario a record nobody
// created before: 10.5555/closed.NNNNN has metadata only, 10.5555/oa.NNNNN
// carries an open-access PDF known to OpenAlex.
const (
	SyntheticDOIClosed = "10.5555/closed."
	SyntheticDOIOpen   = "10.5555/oa."
)

func syntheticDOI(doi string) (DOIRecord, bool) {
	var suffix string
	switch {
	case strings.HasPrefix(doi, SyntheticDOIClosed):
		suffix = strings.TrimPrefix(doi, SyntheticDOIClosed)
	case strings.HasPrefix(doi, SyntheticDOIOpen):
		suffix = strings.TrimPrefix(doi, SyntheticDOIOpen)
	default:
		return DOIRecord{}, false
	}
	if len(suffix) != 5 {
		return DOIRecord{}, false
	}
	rec := DOIRecord{
		DOI:      doi,
		Type:     "journal-article",
		Title:    "Synthetic DOI Fixture " + suffix + ": Minted For One Test Run",
		Abstract: "A synthetic Crossref record generated by fake-scholar for " + doi + ".",
		Authors:  []string{"Syn Thetic", "Doi Fixture"},
		Venue:    "Journal of Deterministic Fixtures",
		Year:     2022,
		Crossref: true,
	}
	if strings.HasPrefix(doi, SyntheticDOIOpen) {
		rec.OpenAlex = &OpenAlexWork{ID: "https://openalex.org/W" + suffix, PDFURL: "https://api.openalex.org/oa/paper-oa-1p.pdf"}
	}
	return rec, true
}

// FindDOI returns the record for a DOI (case-insensitive).
func FindDOI(doi string) (DOIRecord, bool) {
	doi = strings.ToLower(strings.TrimSpace(doi))
	if rec, ok := syntheticDOI(doi); ok {
		return rec, true
	}
	for _, d := range DOIs {
		if strings.ToLower(d.DOI) == doi {
			return d, true
		}
	}
	return DOIRecord{}, false
}
