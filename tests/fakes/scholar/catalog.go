// Synthetic ids let a scenario mint a fresh paper per run on a stand that
// keeps its database: 2350.NNNNN is healthy, 2351.NNNNN refuses the PDF
// (503), 2352.NNNNN answers HTML instead of a PDF. Anything else outside the
// catalog is unknown, as on the real arXiv.
const (
	SyntheticOK          = "2350."
	SyntheticUnavailable = "2351."
	SyntheticNotPDF      = "2352."
)

func synthetic(id string) (Paper, bool) {
	var behavior PDFBehavior
	switch {
	case strings.HasPrefix(id, SyntheticOK):
		behavior = PDFOK
	case strings.HasPrefix(id, SyntheticUnavailable):
		behavior = PDFUnavailable
	case strings.HasPrefix(id, SyntheticNotPDF):
		behavior = PDFNotPDF
	default:
		return Paper{}, false
	}
	if len(id) != len("2350.00000") {
		return Paper{}, false
	}
	pdf := "paper-5p.pdf"
	if behavior == PDFNotPDF {
		pdf = "not-a-pdf.pdf"
	}
	when := time.Date(2023, 5, 1, 10, 0, 0, 0, time.UTC)
	return Paper{
		ID:        id,
		Title:     "Synthetic Fixture Paper " + id + ": Minted For One Test Run",
		Abstract:  "A synthetic arXiv record generated by fake-scholar for id " + id + ".",
		Authors:   []string{"Syn Thetic"},
		Published: when,
		Updated:   when,
		PDF:       pdf,
		Behavior:  behavior,
	}, true
}

// Find returns the catalog entry for an id with or without a version suffix.
func Find(id string) (Paper, bool) {
	id = canonical(id)
	if p, ok := synthetic(id); ok {
		return p, true
	}
	for _, p := range Catalog {
		if p.ID == id {
			return p, true
		}
	}
	return Paper{}, false
}

// Healthy lists papers whose PDF is served normally (what the feed shows).
func Healthy() []Paper {
	out := make([]Paper, 0, len(Catalog))
	for _, p := range Catalog {
		if p.Behavior == PDFOK {
			out = append(out, p)
		}
	}
	return out
}

// DOIRecord is one DOI the fake Crossref (and optionally OpenAlex) knows.
// Crossref answers /works/{doi} with the record; OpenAlex answers
// /works/https://doi.org/{doi} only when OpenAlex is set.
type DOIRecord struct {
	DOI      string
	Type     string // Crossref work type; "journal" etc. are containers
	Title    string
	Abstract string
	Authors  []string
	Venue    string
	Year     int
	Crossref bool // false: Crossref answers 404 (DataCite-only DOI)
	OpenAlex *OpenAlexWork
}

// OpenAlexWork is the subset of an OpenAlex work the catalog reads.
type OpenAlexWork struct {
	ID          string
	LandingPage string // e.g. an arXiv abs page, which the catalog turns into an arXiv paper
	PDFURL      string // an open-access PDF the catalog probes and downloads
}

